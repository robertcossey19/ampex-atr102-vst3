// AmpexCalib — calibrates the anhysteretic-remanence stage per tape stock against the data sheets.
// Output: TapeCalibration.inc lines {kappa, drive (A/m per nWb/m), sens}.
#include "TapeDSP.h"
#include <cstdio>
#include <cmath>
using namespace ampex;

static double thd3FromTable (const AnhTable& t, double A, double& gain)
{
    const int N = 1024; double re1 = 0, im1 = 0, re3 = 0, im3 = 0;
    for (int i = 0; i < N; ++i) { const double w = 2 * kPi * i / N; const double y = t.lookup (A * std::sin (w)); re1 += y * std::cos (w); im1 += y * std::sin (w); re3 += y * std::cos (3 * w); im3 += y * std::sin (3 * w); }
    gain = 2 * std::hypot (re1, im1) / N / A;
    return std::hypot (re3, im3) / std::hypot (re1, im1);
}
static double findLevel (const AnhTable& t, double thd, double lo, double hi) { double g; for (int i = 0; i < 50; ++i) { const double mid = 0.5 * (lo + hi); if (thd3FromTable (t, mid, g) > thd) hi = mid; else lo = mid; } return 0.5 * (lo + hi); }

int main()
{
    std::printf ("// generated by `AmpexCalib` — {kappa, drive (A/m per nWb/m), sens}\n");
    FILE* log = std::fopen ("calib_log.txt", "w");
    for (size_t ti = 0; ti < tapeTable().size(); ++ti)
    {
        const TapeSpec& ts = tapeTable()[ti];
        // target ratio between 3 % level and the level where THD equals the sheet value at ref
        const double targetRatio = ts.molFlux / ts.refFlux;
        double bestErr = 1e9, bestK = 3.0;
        for (double k = 0.0; k <= 4.5; k += 0.05)
        {
            AnhTable t = buildAnhTable (anhFor (ts, (int) ti, k, 0.0));
            const double h3 = findLevel (t, 0.03, 1e-3 * t.Hmax, 0.999 * t.Hmax);
            const double hr = findLevel (t, ts.thdAtRefPct * 0.01, 1e-4 * t.Hmax, h3);
            const double err = std::abs (std::log ((h3 / hr) / targetRatio));
            if (err < bestErr) { bestErr = err; bestK = k; }
        }
        AnhTable t = buildAnhTable (anhFor (ts, (int) ti, bestK, 0.0));
        const double h3 = findLevel (t, 0.03, 1e-3 * t.Hmax, 0.999 * t.Hmax);
        const double drive = h3 / ts.molFlux;
        double gRef, gSmall; const double thdRef = thd3FromTable (t, drive * ts.refFlux, gRef);
        thd3FromTable (t, drive * ts.refFlux * 0.05, gSmall);
        const double sens = 1.0 / (gSmall * drive);
        std::fprintf (log, "%s kappa=%.2f H3%%=%.0f A/m (%.2f Hc) drive=%.4f thd@ref=%.4f%% (sheet %.3f%%) sens=%.4g  Mr(3%%)/Mr=%.3f  part=%.3f\n",
                      ts.name, bestK, h3, h3 / ts.Hc_Am, drive, thdRef * 100, ts.thdAtRefPct, sens, t.lookup (h3) / (ts.Br_T / kMu0), anhFor (ts, (int) ti, bestK, 0).participating());
        for (double b : { -9.0, -6.0, -3.0, 0.0, 3.0, 6.0 })
        {
            AnhTable tb = buildAnhTable (anhFor (ts, (int) ti, bestK, b));
            double g; const double thd = thd3FromTable (tb, drive * ts.refFlux, g);
            double gs; thd3FromTable (tb, drive * ts.refFlux * 0.05, gs);
            std::fprintf (log, "   bias %+.0f dB: level@ref %+.2f dB  small-signal %+.2f dB  THD3@ref %.3f%%\n", b, lin2dB (g * drive * sens), lin2dB (gs * drive * sens), thd * 100);
        }
        for (double dB : { -20.0, -10.0, 0.0, 3.0, 6.0, 9.0, 12.0, 15.0, 18.0, 24.0 })
        { double g; const double A = drive * ts.refFlux * dB2lin (dB); const double thd = thd3FromTable (t, A, g);
          std::fprintf (log, "   level %+5.1f dB re ref: out %+6.2f dB  THD3 %.3f%%\n", dB, lin2dB (g * drive * sens), thd * 100); }
        std::printf ("{ %.2f, %.6f, %.6g },   // %s  thd@ref model %.3f%% / sheet %.3f%%, 3%% at %.1f dB re ref (sheet %.1f)\n", bestK, drive, sens, ts.name, thdRef * 100, ts.thdAtRefPct, lin2dB (h3 / (drive * ts.refFlux)), lin2dB (targetRatio));
        std::fflush (stdout); std::fflush (log);
    }
    std::fclose (log);
    return 0;
}
